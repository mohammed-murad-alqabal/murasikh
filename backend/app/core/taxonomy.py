def get_taxonomy_keys():
    return list(EMOTION_TAXONOMY.keys())

def build_semantic_query(emotion: str) -> str:
    desc = EMOTION_TAXONOMY.get(emotion, "")
    if desc:
        return f"آيات تتحدث عن {emotion}: {desc}"
    return f"آيات عن {emotion} والصبر والطمأنينة"

EMOTION_SEMANTIC_QUERIES = {k: build_semantic_query(k) for k in EMOTION_TAXONOMY.keys()}
