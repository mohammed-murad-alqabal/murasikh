def run():
    embedder = EmbeddingService()
    print(f"Current collection size: {embedder.collection.count()}")

    added = 0
    skipped = 0

    for item in CURATED_VERSES:
        doc_id = f"curated_{item['emotion']}_{item['source'].replace(' ', '_').replace(':', '_')}"
        
        # Check if already exists
        existing = embedder.collection.get(ids=[doc_id])
        if existing['ids']:
            skipped += 1
            continue
        
        metadata = {
            "type": "verse",
            "source": item["source"],
            "tafsir": item["tafsir"],
            "emotion_tag": item["emotion"],
            "is_curated": True,
        }
        
        # Embed enriched text (verse + context for better semantics)
        enriched_text = f"{item['text']} — حالة: {item['emotion']} — {item['tafsir']}"
        embedding = embedder.create_embedding(enriched_text)
        
        embedder.collection.add(
            ids=[doc_id],
            embeddings=[embedding],
            documents=[item["text"]],
            metadatas=[metadata],
        )
        added += 1
        print(f"✓ Added [{item['emotion']}]: {item['source']}")

    print(f"\n✅ Done! Added {added}, Skipped {skipped} (already exist)")
    print(f"New collection size: {embedder.collection.count()}")

if __name__ == "__main__":
    run()
